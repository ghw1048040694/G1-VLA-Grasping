#!/usr/bin/env python3
"""Evaluate phase-blind VLA+WM-MPC on the strict-expert reachable domain.

Unlike the legacy generic slot-jitter evaluator, layouts here are generated by
the same production contract that produced the strict contact experts.  This
keeps each object's calibrated slot-specific feasibility margins and makes the
policy's on-policy states valid candidates for strict recovery supervision.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from collect_g1_language_pick_place_dataset import build_episode_specs
import evaluate_g1_language_pick_place as base
from evaluate_g1_phase_blind_local_wm_mpc import PhaseBlindLocalPolicy


CONTRACT_VERSION = "g1lang_v5_production_reachable_heldout"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--asset", type=Path, required=True)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--world-model-checkpoint", type=Path, required=True)
    parser.add_argument("--train-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--episodes", type=int, default=9)
    parser.add_argument("--seed", type=int, default=20260732)
    parser.add_argument("--control-fps", type=int, default=15)
    parser.add_argument("--duration-s", type=float, default=8.0)
    parser.add_argument(
        "--replan-steps",
        type=int,
        default=7,
        help=(
            "Execute only the current VLA's learned seven-step action chunk before "
            "the next RGB/state replan; no prior chunk may be continued past its horizon."
        ),
    )
    parser.add_argument("--observation-width", type=int, default=160)
    parser.add_argument("--observation-height", type=int, default=120)
    parser.add_argument("--video-width", type=int, default=320)
    parser.add_argument("--video-height", type=int, default=240)
    parser.add_argument(
        "--action-delta-limit-rad",
        type=float,
        default=0.08,
        help="Per-control-step safety limit for direct learned joint targets.",
    )
    parser.add_argument("--body-gain-scale", type=float, default=5.0)
    parser.add_argument("--hand-gain-scale", type=float, default=6.0)
    parser.add_argument("--wm-horizon", type=int, default=1)
    parser.add_argument("--disable-video", action="store_true")
    parser.add_argument("--save-observation-videos", action="store_true")
    parser.add_argument("--device", default="cuda")
    parser.add_argument("--position-jitter-m", type=float, default=0.004)
    parser.add_argument("--center-slot-x-shift-m", type=float, default=0.02)
    parser.add_argument("--red-object-x-shift-m", type=float, default=0.01)
    parser.add_argument("--red-outer-y-jitter-m", type=float, default=0.004)
    parser.add_argument("--yellow-left-x-shift-m", type=float, default=0.01)
    parser.add_argument("--yellow-outer-y-jitter-m", type=float, default=0.001)
    parser.add_argument("--yellow-right-x-shift-m", type=float, default=0.007644)
    parser.add_argument("--yellow-right-y-shift-m", type=float, default=0.012)
    return parser.parse_args()


def reachable_specs(args: argparse.Namespace) -> list[dict]:
    source = build_episode_specs(
        args.episodes,
        args.seed,
        args.position_jitter_m,
        center_slot_x_shift_m=args.center_slot_x_shift_m,
        red_object_x_shift_m=args.red_object_x_shift_m,
        red_outer_y_jitter_m=args.red_outer_y_jitter_m,
        yellow_left_x_shift_m=args.yellow_left_x_shift_m,
        yellow_outer_y_jitter_m=args.yellow_outer_y_jitter_m,
        yellow_right_x_shift_m=args.yellow_right_x_shift_m,
        yellow_right_y_shift_m=args.yellow_right_y_shift_m,
    )
    result = []
    for spec in source:
        result.append(
            {
                "episode_index": spec["episode_index"],
                "scene_index": spec["scene_index"],
                "target_object": spec["target_object"],
                "instruction": spec["instruction"],
                "permutation": tuple(spec["slot_permutation"]),
                "offsets": np.asarray(spec["slot_offsets_xy_m"], dtype=np.float64),
                "layout_mode": "production_reachable",
                "production_spec": spec,
            }
        )
    return result


def main() -> None:
    args = parse_args()
    if args.episodes < 3 or args.episodes % 3:
        raise ValueError("--episodes must be at least three and divisible by three")
    metadata = json.loads((args.train_root / "meta/info.json").read_text())
    policy = PhaseBlindLocalPolicy(
        args.checkpoint,
        args.world_model_checkpoint,
        args.device,
        args.control_fps,
        args.wm_horizon,
        args.action_delta_limit_rad,
    )
    args.disable_assisted_grasp = True
    args.output_dir.mkdir(parents=True, exist_ok=True)
    reports = []
    specs = reachable_specs(args)
    for spec in specs:
        report = base.run_episode(policy, spec, args, metadata["features"]["action"]["names"])
        report.update(
            predicted_target_probabilities=policy.last_target_probabilities,
            predicted_active_arm_probabilities=policy.last_active_arm_probabilities,
            camera_object_position_m=policy.last_object_position,
            measured_finger_contact_site_position_m=policy.last_contact_site_position,
            measured_tactile_contact=policy.last_tactile_contact,
            camera_tracking=policy.camera_tracker_reports,
            world_model_candidates=policy.candidate_reports,
            production_spec=spec["production_spec"],
        )
        report_path = args.output_dir / f"episode_{spec['episode_index']:04d}" / "summary.json"
        report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        reports.append(report)
    contacts = [report["hand_object_contact_candidate_steps"] > 0 for report in reports]
    language = [
        report["world_model_candidates"][-1]["target_index"]
        == base.OBJECT_NAMES.index(report["target_object"])
        for report in reports
    ]
    summary = {
        "experiment": "G1LANG-phase-blind-local-vla-wm-mpc-production-reachable-gate",
        "reachable_contract_version": CONTRACT_VERSION,
        "checkpoint": str(args.checkpoint),
        "world_model_checkpoint": str(args.world_model_checkpoint),
        "episodes": len(reports),
        "camera_inputs": [
            "observation.images.head",
            "observation.images.left_wrist",
            "observation.images.right_wrist",
        ],
        "language_input": "tokenized task text",
        "state_input_dim": 31,
        "model_action_output_dim": 31,
        "candidate_selection_mode": "phase-blind learned world-model finger-geometry distance MPC; contact audit-only",
        "current_plan_execution": {
            "replan_steps": args.replan_steps,
            "contract": (
                "execute the selected current VLA action chunk only within its "
                "seven-step horizon, then re-observe and replan"
            ),
            "stale_previous_plan_continuation": False,
        },
        "action_delta_limit_rad": args.action_delta_limit_rad,
        "layout_contract": {
            "generator": "collect_g1_language_pick_place_dataset.build_episode_specs",
            "seed": args.seed,
            "position_jitter_m": args.position_jitter_m,
            "center_slot_x_shift_m": args.center_slot_x_shift_m,
            "red_object_x_shift_m": args.red_object_x_shift_m,
            "red_outer_y_jitter_m": args.red_outer_y_jitter_m,
            "yellow_left_x_shift_m": args.yellow_left_x_shift_m,
            "yellow_outer_y_jitter_m": args.yellow_outer_y_jitter_m,
            "yellow_right_x_shift_m": args.yellow_right_x_shift_m,
            "yellow_right_y_shift_m": args.yellow_right_y_shift_m,
        },
        "assisted_grasp_enabled": False,
        "equality_constraints": False,
        "magnet_enabled": False,
        "privileged_positions_at_inference": False,
        "reports": reports,
        "language_target_accuracy": float(np.mean(language)),
        "real_contact_rate": float(np.mean(contacts)),
        "no_grasp_rate": float(np.mean([report["grabbed_object"] is None for report in reports])),
        "full_pick_place_success_rate": float(np.mean([report["task_success"] for report in reports])),
        "mean_joint_limit_violation_fraction": float(
            np.mean([report["joint_limit_violation_fraction"] for report in reports])
        ),
    }
    summary["passed"] = bool(
        all(contacts)
        and summary["language_target_accuracy"] >= 0.80
        and summary["mean_joint_limit_violation_fraction"] <= 0.01
    )
    (args.output_dir / "summary.json").write_text(
        json.dumps(summary, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps({key: value for key, value in summary.items() if key != "reports"}, indent=2))


if __name__ == "__main__":
    main()
